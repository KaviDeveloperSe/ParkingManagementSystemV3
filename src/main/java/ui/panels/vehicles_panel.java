        private void loadCustomersToComboBox() {

        cmb_owner.removeAllItems();

        List<customer_model> customers =
                customerDAO.getAllCustomers();

        for (customer_model customer : customers) {

                String item =
                        customer.get_customer_model_customer_id()
                        + " - "
                        + customer.get_customer_model_name();

                cmb_owner.addItem(item);
        }
        }
        
        private void loadVehicles() {

        List<vehicle_model> vehicles =
                vehicleDAO.getAllVehicles();

        displayVehicles(vehicles);
        }
        
        private void displayVehicles(
                List<vehicle_model> vehicles) {

        DefaultTableModel tableModel =
                (DefaultTableModel)
                        tbl_vehicles.getModel();

        tableModel.setRowCount(0);

        SimpleDateFormat dateFormat =
                new SimpleDateFormat(
                        "yyyy-MM-dd HH:mm"
                );

        for (vehicle_model vehicle : vehicles) {

                Timestamp createdAt =
                        vehicle.getCreated_at();

                String registered = "";

                if (createdAt != null) {

                registered =
                        dateFormat.format(
                                createdAt
                        );
                }

                tableModel.addRow(
                        new Object[]{
                        vehicle.getVehicle_id(),
                        vehicle.getRegistration_number(),
                        vehicle.getVehicle_type(),
                        vehicle.getBrand(),
                        vehicle.getModel(),
                        vehicle.getCustomer_name(),
                        registered
                        }
                );
        }

        tbl_vehicles.clearSelection();

        btn_edit.setEnabled(false);
        btn_delete.setEnabled(false);
        }
        
        private void searchVehicles() {

        String keyword =
                txt_search
                        .getText()
                        .trim();

        List<vehicle_model> vehicles;

        if (keyword.isEmpty()) {

                vehicles =
                        vehicleDAO.getAllVehicles();

        } else {

                vehicles =
                        vehicleDAO.searchVehicles(
                                keyword
                        );
        }

        displayVehicles(vehicles);
        }
        
