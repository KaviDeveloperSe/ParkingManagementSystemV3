        private void saveVehicle() {

        String registration =
                txt_registration
                        .getText()
                        .trim()
                        .toUpperCase();

        String brand =
                txt_brand
                        .getText()
                        .trim();

        String model =
                txt_model
                        .getText()
                        .trim();


        if (cmb_owner.getSelectedItem() == null) {

                JOptionPane.showMessageDialog(
                        vehicle_dialog,
                        "Please select a customer.",
                        "Validation Error",
                        JOptionPane.WARNING_MESSAGE
                );

                return;
        }


        if (registration.isEmpty()) {

                showValidationError(
                        "Registration number is required.",
                        txt_registration
                );

                return;
        }


        if (!registration.matches(
                "[A-Z0-9\\-]{2,20}"
        )) {

                showValidationError(
                        "Enter a valid registration number.",
                        txt_registration
                );

                return;
        }


        if (cmb_type.getSelectedItem() == null) {

                JOptionPane.showMessageDialog(
                        vehicle_dialog,
                        "Please select a vehicle type.",
                        "Validation Error",
                        JOptionPane.WARNING_MESSAGE
                );

                return;
        }


        if (brand.isEmpty()) {

                showValidationError(
                        "Vehicle brand is required.",
                        txt_brand
                );

                return;
        }


        if (model.isEmpty()) {

                showValidationError(
                        "Vehicle model is required.",
                        txt_model
                );

                return;
        }


        Integer excludedVehicleId =
                editMode
                        ? selectedVehicleId
                        : null;


        if (vehicleDAO.registrationExists(
                registration,
                excludedVehicleId)) {

                showValidationError(
                        "This registration number already exists.",
                        txt_registration
                );

                return;
        }


        String selectedCustomer =
                cmb_owner.getSelectedItem().toString();

        int customerId =
                Integer.parseInt(
                        selectedCustomer
                                .substring(
                                        0,
                                        selectedCustomer.indexOf(" - ")
                                )
                );

        String vehicleType =
                cmb_type.getSelectedItem().toString();


        if (editMode) {

                updateVehicle(
                        registration,
                        vehicleType,
                        brand,
                        model,
                        customerId
                );

        } else {

                addVehicle(
                        registration,
                        vehicleType,
                        brand,
                        model,
                        customerId
                );
        }
        }
        
        private void addVehicle(
                String registration,
                String vehicleType,
                String brand,
                String model,
                int customerId) {

        vehicle_model vehicle =
                new vehicle_model(
                        registration,
                        vehicleType,
                        brand,
                        model,
                        customerId
                );

        boolean success =
                vehicleDAO.addVehicle(
                        vehicle
                );

        if (success) {

                JOptionPane.showMessageDialog(
                        vehicle_dialog,
                        "Vehicle added successfully.",
                        "Add Vehicle",
                        JOptionPane.INFORMATION_MESSAGE
                );

                closeVehicleDialog();

                refreshData();

        } else {

                JOptionPane.showMessageDialog(
                        vehicle_dialog,
                        "Unable to add vehicle.",
                        "Add Vehicle Error",
                        JOptionPane.ERROR_MESSAGE
                );
        }
        }
        
        private void openEditVehicleDialog() {

        int selectedRow =
                tbl_vehicles.getSelectedRow();

        if (selectedRow == -1) {

                JOptionPane.showMessageDialog(
                        this,
                        "Please select a vehicle first.",
                        "No Vehicle Selected",
                        JOptionPane.WARNING_MESSAGE
                );

                return;
        }


        selectedVehicleId =
                Integer.parseInt(
                        tbl_vehicles
                                .getValueAt(
                                        selectedRow,
                                        0
                                )
                                .toString()
                );


        vehicle_model vehicle =
                vehicleDAO.getVehicleById(
                        selectedVehicleId
                );


        if (vehicle == null) {

                JOptionPane.showMessageDialog(
                        this,
                        "Vehicle could not be found.",
                        "Vehicle Error",
                        JOptionPane.ERROR_MESSAGE
                );

                return;
        }


        editMode = true;

        loadCustomersToComboBox();


        txt_registration.setText(
                vehicle.getRegistration_number()
        );

        txt_brand.setText(
                vehicle.getBrand()
        );

        txt_model.setText(
                vehicle.getModel()
        );


        cmb_type.setSelectedItem(
                vehicle.getVehicle_type()
        );


        selectCustomer(
                vehicle.getCustomer_id()
        );


        vehicle_dialog.setTitle(
                "Edit Vehicle"
        );

        btn_save.setText(
                "Update"
        );


        vehicle_dialog.setLocationRelativeTo(
                this
        );

        vehicle_dialog.setVisible(
                true
        );
        }
        
        private void selectCustomer(int customerId) {

        String prefix = customerId + " - ";

        for (int i = 0; i < cmb_owner.getItemCount(); i++) {

                String item = cmb_owner.getItemAt(i);

                if (item != null && item.startsWith(prefix)) {
                cmb_owner.setSelectedIndex(i);
                return;
                }
        }
        }
        
        private void updateVehicle(
                String registration,
                String vehicleType,
                String brand,
                String model,
                int customerId) {

        vehicle_model existing =
                vehicleDAO.getVehicleById(
                        selectedVehicleId
                );

        if (existing == null) {

                JOptionPane.showMessageDialog(
                        vehicle_dialog,
                        "Vehicle could not be found.",
                        "Update Vehicle",
                        JOptionPane.ERROR_MESSAGE
                );

                return;
        }


        vehicle_model vehicle =
                new vehicle_model(

                        selectedVehicleId,

                        registration,

                        vehicleType,

                        brand,

                        model,

                        customerId,

                        existing.getCustomer_name(),

                        existing.getCreated_at()
                );


        boolean success =
                vehicleDAO.updateVehicle(
                        vehicle
                );


        if (success) {

                JOptionPane.showMessageDialog(
                        vehicle_dialog,
                        "Vehicle updated successfully.",
                        "Update Vehicle",
                        JOptionPane.INFORMATION_MESSAGE
                );

                closeVehicleDialog();

                refreshData();

        } else {

                JOptionPane.showMessageDialog(
                        vehicle_dialog,
                        "Unable to update vehicle.",
                        "Update Vehicle Error",
                        JOptionPane.ERROR_MESSAGE
                );
        }
        }
        
        private void deleteVehicle() {

        int selectedRow =
                tbl_vehicles.getSelectedRow();


        if (selectedRow == -1) {

                JOptionPane.showMessageDialog(
                        this,
                        "Please select a vehicle first.",
                        "No Vehicle Selected",
                        JOptionPane.WARNING_MESSAGE
                );

                return;
        }


        int vehicleId =
                Integer.parseInt(
                        tbl_vehicles
                                .getValueAt(
                                        selectedRow,
                                        0
                                )
                                .toString()
                );


        String registration =
                tbl_vehicles
                        .getValueAt(
                                selectedRow,
                                1
                        )
                        .toString();


        /*
        * Only keep this check if your DB really
        * has parking_sessions.
        */
        if (vehicleDAO.vehicleHasActiveParking(
                vehicleId)) {

                JOptionPane.showMessageDialog(
                        this,

                        "Cannot delete vehicle "
                        + registration
                        + ".\n\n"
                        + "The vehicle is currently parked. Complete its exit first.",

                        "Vehicle Has Parking Records",

                        JOptionPane.WARNING_MESSAGE
                );

                return;
        }


        int confirmation =
                JOptionPane.showConfirmDialog(
                        this,

                        "Are you sure you want to permanently delete "
                        + registration
                        + "?\n\nCompleted parking history for this vehicle will also be deleted.",

                        "Delete Vehicle",

                        JOptionPane.YES_NO_OPTION,

                        JOptionPane.WARNING_MESSAGE
                );


        if (
                confirmation
                        != JOptionPane.YES_OPTION
        ) {

                return;
        }


        boolean success =
                vehicleDAO.deleteVehicle(
                        vehicleId
                );


        if (success) {

                JOptionPane.showMessageDialog(
                        this,
                        "Vehicle deleted successfully.",
                        "Delete Vehicle",
                        JOptionPane.INFORMATION_MESSAGE
                );

                refreshData();

        } else {

                JOptionPane.showMessageDialog(
                        this,

                        "Unable to delete vehicle.\n"
                        + "The vehicle may still have active parking, "
                        + "or the database operation failed.",

                        "Delete Vehicle Error",

                        JOptionPane.ERROR_MESSAGE
                );
        }
        }
        
